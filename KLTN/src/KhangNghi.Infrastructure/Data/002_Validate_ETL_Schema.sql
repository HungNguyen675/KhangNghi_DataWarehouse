FROM @Required r
LEFT JOIN sys.tables t ON t.name=r.TableName AND t.schema_id=SCHEMA_ID(N'dbo')
LEFT JOIN sys.columns c ON c.object_id=t.object_id AND c.name=r.ColumnName
WHERE c.column_id IS NULL OR (TYPE_NAME(c.system_type_id)<>r.TypeName
   AND NOT (r.TableName LIKE N'Sys[_]%' AND r.TypeName=N'datetime2'
            AND TYPE_NAME(c.system_type_id)=N'datetime'))
   -- Wider compatible string columns (including max) can hold the required payload.
   -- A required max column must still be max; a narrower finite column is rejected.
