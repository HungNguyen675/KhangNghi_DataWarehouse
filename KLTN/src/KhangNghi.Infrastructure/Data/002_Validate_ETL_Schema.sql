       ((r.MaxLength=-1 AND c.max_length<>-1)
        OR (r.MaxLength<>-1 AND c.max_length<>-1 AND c.max_length<r.MaxLength)))
   OR c.is_identity<>r.IsIdentity
UNION ALL
